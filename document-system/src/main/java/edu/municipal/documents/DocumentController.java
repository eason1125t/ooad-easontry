// Business reads/writes use session identity and a fresh remote authorization before each operation.
// Owns H2 documents, optimistic versions and transactional audit; never connects to RBAC's MySQL.
package edu.municipal.documents;
import jakarta.annotation.PostConstruct;
import jakarta.servlet.http.HttpServletRequest;
import java.util.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/office-api")
public class DocumentController {
    public static final String READ="office.documents:read", UPDATE="office.documents:update";
    private final OfficeSecurity security;private final RbacClient rbac;private final JdbcTemplate db;private final TransactionTemplate transaction;
    public DocumentController(OfficeSecurity security,RbacClient rbac,JdbcTemplate db,PlatformTransactionManager manager) {this.security=security;this.rbac=rbac;this.db=db;transaction=new TransactionTemplate(manager);}
    @PostConstruct void initialize() {
        db.execute("CREATE TABLE IF NOT EXISTS office_document(id VARCHAR(20) PRIMARY KEY,title VARCHAR(120) NOT NULL,content VARCHAR(10000) NOT NULL,version BIGINT NOT NULL DEFAULT 0)");
        db.execute("CREATE TABLE IF NOT EXISTS office_change(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,employee_id BIGINT NOT NULL,document_id VARCHAR(20) NOT NULL,request_id VARCHAR(32) NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        for(var seed:List.of(List.of("DOC-001","道路养护工作通知（合成）","本周开展道路养护巡查，请按计划登记问题并提交复核。"),List.of("DOC-002","桥梁巡检安排（合成）","请项目组按照巡检清单记录桥梁设施状态，所有内容均为合成验证数据。"))) {
            if(db.queryForObject("SELECT COUNT(*) FROM office_document WHERE id=?",Long.class,seed.getFirst())==0)db.update("INSERT INTO office_document(id,title,content) VALUES(?,?,?)",seed.toArray());
        }
    }
    @GetMapping("/health") public Object health() {db.queryForObject("SELECT 1",Integer.class);return Map.of("status","UP");}
    @GetMapping("/profiles") public Object profiles() {return security.profiles();}
    @PostMapping("/mock-session") public Object login(@RequestBody Map<String,Object> body,HttpServletRequest request) {return security.login(body,request);}
    @GetMapping("/me") public Object me(HttpServletRequest request) {return security.me(request);}
    @PostMapping("/logout") public void logout(HttpServletRequest request) {request.getSession(false).invalidate();}
    @GetMapping("/permissions") public Object permissions(HttpServletRequest request) {
        var result=rbac.check(security.employee(request),List.of(READ,UPDATE));return Map.of("permissions",result.values(),"requestId",result.requestId());
    }
    @GetMapping("/documents") public Object documents(HttpServletRequest request) {
        String requestId=rbac.require(security.employee(request),READ);
        return Map.of("items",db.query("SELECT id,title,content,version FROM office_document ORDER BY id",(row,index)->Map.of("id",row.getString("id"),"title",row.getString("title"),"content",row.getString("content"),"version",row.getLong("version"))),"requestId",requestId);
    }
    @PutMapping("/documents/{id}") public Object update(@PathVariable String id,@RequestBody Map<String,Object> body,HttpServletRequest request) {
        long employee=security.employee(request);String requestId=rbac.require(employee,UPDATE);
        if(!body.keySet().equals(Set.of("title","content","version")) || !(body.get("title") instanceof String title) || title.isBlank() || title.length()>120
            || !(body.get("content") instanceof String content) || content.isBlank() || content.length()>10000
            || !(body.get("version") instanceof Number version) || version.longValue()<0 || version.doubleValue()!=version.longValue()) throw new OfficeProblem(400,"INVALID_INPUT","请填写标题、正文和有效版本号");
        return transaction.execute(status->{
            if(db.update("UPDATE office_document SET title=?,content=?,version=version+1 WHERE id=? AND version=?",title,content,id,version.longValue())!=1)throw new OfficeProblem(409,"VERSION_CONFLICT","公文已变化，请重新读取后保存");
            db.update("INSERT INTO office_change(employee_id,document_id,request_id) VALUES(?,?,?)",employee,id,requestId);
            return Map.of("saved",true,"version",version.longValue()+1,"requestId",requestId);
        });
    }
}
